const BY_SYMBOL = new Map(STOCK_UNIVERSE.map((entry) => [entry.symbol, entry]));

export function getUniverseEntry(symbol: string): UniverseEntry | undefined {
  return BY_SYMBOL.get(symbol);
}

/** The public contract: nothing of the simulation parameters leaks out. */
export function toStock(entry: UniverseEntry): Stock {
  return {
    symbol: entry.symbol,
    name: entry.name,
    exchange: entry.exchange,
    sector: entry.sector,
    currency: entry.currency,
  };
}
