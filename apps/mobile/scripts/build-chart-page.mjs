// Writes the chart library as a string module, so the WebView page can hold it inline and work
// with no network. The output is generated and not committed (it is about 200 KB); every package
// script that needs it runs this first, and it does nothing when the output is already current.
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
// The package's exports map does not list the standalone build, so the folder is found through
// its package.json, which it does list.
const source = join(
  dirname(require.resolve('lightweight-charts/package.json')),
  'dist/lightweight-charts.standalone.production.js',
);
const output = join(root, 'src/features/stocks/generated/chart-library.ts');

if (existsSync(output) && statSync(output).mtimeMs >= statSync(source).mtimeMs) {
  process.exit(0);
}

mkdirSync(dirname(output), { recursive: true });
writeFileSync(
  output,
  `// Generated by scripts/build-chart-page.mjs from lightweight-charts. Not committed.\n` +
    `export const chartLibrarySource: string = ${JSON.stringify(readFileSync(source, 'utf8'))};\n`,
);
